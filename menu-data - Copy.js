const remainingMenuSlots = { veg: 10, "non-veg": 10, desserts: 10, drinks: 10 };
window.restaurantMenuItems.forEach((item) => {
  if (remainingMenuSlots[item.category] > 0) remainingMenuSlots[item.category]--;
});
const visibleSupplementaryMenuItems = supplementaryMenuItems.filter(([category]) => {
  if (remainingMenuSlots[category] <= 0) return false;
  remainingMenuSlots[category]--;
  return true;
});

const menuPhotosByName = new Map(window.restaurantMenuItems.map((item) => [item.name, item.image]));
const photoUsageCounts = new Map();
const menuPhotosByCategory = new Map();
window.restaurantMenuItems.forEach((item) => {
  photoUsageCounts.set(item.image, (photoUsageCounts.get(item.image) || 0) + 1);
  if (!menuPhotosByCategory.has(item.category)) menuPhotosByCategory.set(item.category, []);
  menuPhotosByCategory.get(item.category).push(item.image);
});

window.restaurantMenuItems.push(...visibleSupplementaryMenuItems.map(([category, name, price, description, photoName]) => {
  const photo = menuPhotoOverrides[name];
  let image = photo ? photo.image : menuPhotosByName.get(photoName);
  if (!image) throw new Error(`Missing menu photo reference: ${photoName}`);

  if (!photo) {
    const categoryPhotos = menuPhotosByCategory.get(category) || [];
    const leastUsedCount = Math.min(...categoryPhotos.map((candidate) => photoUsageCounts.get(candidate) || 0));
    if ((photoUsageCounts.get(image) || 0) > leastUsedCount + 1) {
      image = categoryPhotos.find((candidate) => (photoUsageCounts.get(candidate) || 0) === leastUsedCount);
    }
  }
  photoUsageCounts.set(image, (photoUsageCounts.get(image) || 0) + 1);

  const photoType = category === "drinks" ? "drink" : category === "desserts" ? "dessert" : "dish";
  return {
    category,
    name,
    price,
    description,
    image,
    ...(photo ? {
      imageSource: photo.source,
      imageCredit: photo.artist,
      imageLicense: photo.license
    } : {}),
    alt: photo ? `Photo of ${name}` : `Illustrative ${photoType} photo for ${name.toLowerCase()}`
  };
}));
